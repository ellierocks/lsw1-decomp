#!/usr/bin/env python3
"""
GC unit-boundary leads from the Japanese PC 1.0 exe. Evidence only.

MSVC links each object file contiguously, so an x86 function lying between the
first and last function that load the same assert path (`.\\creature.c`) belongs
to that file. Projecting those file extents through the GC<->x86 pairs onto GC
address order shows where one source file ends and the next begins:

  - a lead is the GC address interval between the last pair labelled with one
    file and the first pair labelled with the next; the true boundary lies in it;
  - `conflict` marks a lead whose interval excludes the current split boundary
    between two units, or that falls inside one unit (an absorbed TU).

Reads build/pc_analysis/gc_pc_anchors.tsv and pc_source_files.tsv (run
tools/pc_gc_anchors.py first) and config/GL5E4F/splits.txt; writes
build/pc_analysis/pc_split_leads.tsv. Never edits splits: confirm a lead from GC
code (path loads, matched C) and record it per docs/build_config.md. Inferred
pairs can be wrong, so a lead resting on one pair is weak.

    python3 tools/pc_gc_splits.py [--all]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pc_gc_anchors import OUT_DIR, ROOT, load_anchors  # noqa: E402

SPLITS = ROOT / "config/GL5E4F/splits.txt"
TEXT_RE = re.compile(r"\.text\s+start:0x([0-9A-Fa-f]+)\s+end:0x([0-9A-Fa-f]+)")


def text_units(text: str) -> list[tuple[int, int, str]]:
    """[(start, end, unit)] for every split with a .text range, sorted."""
    out, unit = [], None
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if not raw.startswith((" ", "\t")):
            unit = None if line == "Sections:" else line.rstrip(":")
            continue
        m = TEXT_RE.match(line)
        if m and unit:
            out.append((int(m.group(1), 16), int(m.group(2), 16), unit))
    return sorted(out)


def file_extents(text: str) -> dict[str, tuple[int, int]]:
    """{source path: (first, last x86 function loading it)} from pc_source_files.tsv."""
    out = {}
    for line in text.splitlines():
        cols = line.split("\t")
        if len(cols) < 2 or not cols[1].startswith("0x"):
            continue
        fns = [int(f, 16) for f in cols[1].split(",")]
        out[cols[0]] = (min(fns), max(fns))
    return out


def label(pc: int, extents: dict[str, tuple[int, int]]) -> str | None:
    hits = [path for path, (lo, hi) in extents.items() if lo <= pc <= hi]
    return hits[0] if len(hits) == 1 else None


def unit_at(addr: int, units: list[tuple[int, int, str]]) -> str | None:
    return next((u for s, e, u in units if s <= addr < e), None)


def leads(pairs: dict[int, tuple[int, str]], extents, units) -> list[dict]:
    """Label runs in GC order and the boundary interval between consecutive runs."""
    runs: list[dict] = []
    for gc in sorted(pairs):
        path = label(pairs[gc][0], extents)
        if path is None:
            continue
        if runs and runs[-1]["path"] == path:
            runs[-1]["last"] = gc
            runs[-1]["count"] += 1
        else:
            runs.append({"path": path, "first": gc, "last": gc, "count": 1})
    out = []
    for a, b in zip(runs, runs[1:]):
        ua, ub = unit_at(a["last"], units), unit_at(b["first"], units)
        if ua == ub:
            conflict = "inside " + (ua or "unsplit code")
        else:
            cut = next((s for s, _, u in units if u == ub), None) if ub else None
            conflict = "" if cut is not None and a["last"] < cut <= b["first"] else "boundary outside interval"
        out.append({"after": a, "before": b, "unit_after": ua, "unit_before": ub, "conflict": conflict})
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--all", action="store_true", help="print every lead, not only conflicts")
    args = parser.parse_args()
    pairs = load_anchors()
    sources = OUT_DIR / "pc_source_files.tsv"
    if pairs is None or not sources.exists():
        print("error: run python3 tools/pc_gc_anchors.py first", file=sys.stderr)
        return 1
    units = text_units(SPLITS.read_text())
    rows = leads(pairs, file_extents(sources.read_text()), units)

    lines = ["# Generated by tools/pc_gc_splits.py. Evidence only; never edit splits from it alone.",
             "gc_after\tgc_before\tpath_after\tpairs_after\tpath_before\tpairs_before\tunit_after\tunit_before\tconflict"]
    for r in rows:
        a, b = r["after"], r["before"]
        lines.append(f"0x{a['last']:08X}\t0x{b['first']:08X}\t{a['path']}\t{a['count']}\t{b['path']}\t{b['count']}"
                     f"\t{r['unit_after'] or '-'}\t{r['unit_before'] or '-'}\t{r['conflict'] or '-'}")
    out = OUT_DIR / "pc_split_leads.tsv"
    out.write_text("\n".join(lines) + "\n")

    shown = [r for r in rows if args.all or r["conflict"]]
    for r in shown:
        a, b = r["after"], r["before"]
        print(f"0x{a['last']:08X}..0x{b['first']:08X}  {a['path']} ({a['count']}) -> {b['path']} ({b['count']})"
              f"  [{r['unit_after'] or '-'} | {r['unit_before'] or '-'}]  {r['conflict'] or 'ok'}")
    print(f"{len(rows)} leads, {sum(1 for r in rows if r['conflict'])} conflicting; wrote {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
