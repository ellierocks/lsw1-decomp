static int adpcmStride1;
static int adpcmStride2;

void fn_80189934(HVQM4AdpcmState* state, const u8* code, s16* out,
                       u32 flags, u32 samples, int track) {
  u32 bytes;
  const u8* cursor;
  int packed;
  int delta;
  if (code == NULL) {
    return;
  }
  if (!(samples & 1)) {
    bytes = samples >> 1;
  } else {
    bytes = (samples >> 1) + 1;
  }
  if (flags == 1) {
    adpcmStride1 = track;
    bytes += 2;
  } else if (flags == 3) {
    adpcmStride1 = track;
    bytes += 3;
  }
  if (bytes & 1) {
    bytes++;
  }
  bytes *= adpcmStride1;
  cursor = code + bytes;
  if (flags == 1) {
    int sample, index;
    samples--;
    sample = cursor[0] << 8;
    index = cursor[1];
    cursor += 2;
    state->sample = (s16)(sample | (index & 0x80));
    state->index = index & 0x7f;
    out[0] = out[1] = state->sample;
    out += 2;
  } else if (flags == 3) {
    samples--;
    state->sample = (s16)((cursor[0] << 8) | cursor[1]);
    state->index = cursor[2];
    cursor += 3;
    out[0] = out[1] = state->sample;
    out += 2;
  }
  {
    int sample = state->sample;
    int index = state->index;
    while (samples != 0) {
      packed = *cursor;
      delta = (packed >> 4) & 7;
      if (!(packed & 0x80)) {
        sample += adpcmTable[index][delta];
        if (sample > 32767) {
          sample = 32767;
        }
      } else {
        sample -= adpcmTable[index][delta];
        if (sample < -32768) {
          sample = -32768;
        }
      }
      index = adpcmIndexTable[index][delta];
      out[1] = out[0] = sample;
      if (samples == 1) {
        break;
      }
      delta = packed & 7;
      if (!(packed & 8)) {
        sample += adpcmTable[index][delta];
        if (sample > 32767) {
          sample = 32767;
        }
      } else {
        sample -= adpcmTable[index][delta];
        if (sample < -32768) {
          sample = -32768;
        }
      }
      index = adpcmIndexTable[index][delta];
      cursor++;
      out[3] = out[2] = sample;
      samples -= 2;
      out += 4;
    }
    state->sample = sample;
    state->index = index;
  }
}

void fn_80189B30(HVQM4AdpcmState* state, const u8* code, s16* out,
                       u32 flags, u32 samples, int track) {
  u32 bytes;
  const u8* cursor;
  u8 packed;
  int delta;
  if (code == NULL) {
    return;
  }
  bytes = samples;
  if (flags == 1) {
    adpcmStride2 = track;
    bytes += 4;
  } else if (flags == 3) {
    adpcmStride2 = track;
    bytes += 6;
  }
  if (bytes & 1) {
    bytes++;
  }
  bytes *= adpcmStride2;
  cursor = code + bytes;
  if (flags == 1) {
    u8 header[4];
    samples--;
    header[0] = cursor[0];
    header[1] = cursor[1];
    state[0].sample = (s16)((header[0] << 8) | (header[1] & 0x80));
    state[0].index = header[1] & 0x7f;
    header[2] = cursor[2];
    header[3] = cursor[3];
    cursor += 4;
    state[1].sample = (s16)((header[2] << 8) | (header[3] & 0x80));
    state[1].index = header[3] & 0x7f;
    out[1] = state[0].sample;
    out[0] = state[1].sample;
    out += 2;
  } else if (flags == 3) {
    samples--;
    state[0].sample = (s16)((cursor[0] << 8) | cursor[1]);
    state[0].index = cursor[2];
    state[1].sample = (s16)((cursor[3] << 8) | cursor[4]);
    state[1].index = cursor[5];
    cursor += 6;
    out[1] = state[0].sample;
    out[0] = state[1].sample;
    out += 2;
  }
  {
    int sample1 = state[0].sample;
    int index1 = state[0].index;
    int sample2 = state[1].sample;
    int index2 = state[1].index;
    for (; samples != 0; samples--) {
      packed = *cursor;
      delta = (packed >> 4) & 7;
      if (!(packed & 0x80)) {
        sample1 += adpcmTable[index1][delta];
        if (sample1 > 32767) {
          sample1 = 32767;
        }
      } else {
        sample1 -= adpcmTable[index1][delta];
        if (sample1 < -32768) {
          sample1 = -32768;
        }
      }
      index1 = adpcmIndexTable[index1][delta];
      out[1] = sample1;
      delta = packed & 7;
      if (!(packed & 8)) {
        sample2 += adpcmTable[index2][delta];
        if (sample2 > 32767) {
          sample2 = 32767;
        }
      } else {
        sample2 -= adpcmTable[index2][delta];
        if (sample2 < -32768) {
          sample2 = -32768;
        }
      }
      index2 = adpcmIndexTable[index2][delta];
      cursor++;
      out[0] = sample2;
      out += 2;
    }
    state[0].sample = sample1;
    state[0].index = index1;
    state[1].sample = sample2;
    state[1].index = index2;
  }
}

