/* Retail places adpcmStride4 4 bytes into this TU's 8-aligned .sbss; nothing
 * in GL5E4F references the word before it (sbssUnused_ACC8). */
static int sbssUnused_ACC8;
static int adpcmStride4;

void fn_80189FFC(HVQM4AdpcmState* state, const u8* code, s16* out,
                       u32 flags, u32 samples, int track) {
  int initial;
  int* table;
  u32 bytes;
  int sample1;
  int sample2;
  if (code == NULL) {
    return;
  }
  if (flags & 0x80) {
    initial = 1;
  } else {
    initial = 0;
  }
  table = adpcm4Table[flags & 3];
  bytes = samples * 2;
  if (initial) {
    adpcmStride4 = track;
    bytes += 4;
  }
  bytes *= adpcmStride4;
  code += bytes;
  if (initial) {
    state[0].sample = (s16)((code[0] << 8) | code[1]);
    state[1].sample = (s16)((code[2] << 8) | code[3]);
    code += 4;
  }
  sample1 = state[0].sample;
  sample2 = state[1].sample;
  for (; samples != 0; samples--) {
    sample1 += table[code[0]];
    if (sample1 < -32768) {
      sample1 = -32768;
    }
    if (sample1 > 32767) {
      sample1 = 32767;
    }
    out[1] = sample1;
    sample2 += table[code[1]];
    if (sample2 < -32768) {
      sample2 = -32768;
    }
    if (sample2 > 32767) {
      sample2 = 32767;
    }
    out[0] = sample2;
    code += 2;
    out += 2;
  }
  state[0].sample = sample1;
  state[1].sample = sample2;
}
